import type { RadarEntry } from './queries.js';

/** Escapes text for HTML. */
const esc = (s: string): string =>
  s.replace(
    /[&<>"']/g,
    (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c] ?? c,
  );

/** Human labels of the actionability tiers. */
export const TIER_LABELS: Readonly<Record<RadarEntry['actionability']['tier'], string>> = {
  open_window: 'Open consultation / feedback window',
  upcoming_vote: 'Upcoming vote',
  standstill: 'Standstill period',
  in_procedure: 'In procedure',
  adopted: 'Adopted',
  information: 'Information',
};

/** Input of the digest renderer. */
export interface DigestInput {
  /** First day of the week (ISO). */
  readonly weekStart: string;
  /** Last day of the week (ISO). */
  readonly weekEnding: string;
  /** Selected countries. */
  readonly countries: readonly string[];
  /** Selected NACE codes. */
  readonly naceCodes: readonly string[];
  /** Ranked entries to include. */
  readonly entries: readonly RadarEntry[];
  /** Entries first seen this week. */
  readonly newKeys: ReadonlySet<string>;
  /** Denominator. */
  readonly groupsChecked: number;
}

/** Renders an e-mail-ready HTML digest (inline styles, tables, no scripts); pure. */
export const renderDigest = (d: DigestInput): string => {
  const row = (e: RadarEntry) => {
    const date = e.actionability.date ? ` · ${e.actionability.date}` : '';
    const trail = e.sourceTrail
      .map((t) => (t.url ? `<a href="${esc(t.url)}">${esc(t.externalId)}</a>` : esc(t.externalId)))
      .join(', ');
    return `<tr><td style="padding:12px 0;border-bottom:1px solid #ddd">
<div style="font-size:12px;color:#555">${esc(TIER_LABELS[e.actionability.tier])}${esc(date)} · ${esc(e.jurisdiction)} · ${esc(e.verdict)}${d.newKeys.has(e.groupKey) ? ' · <b style="color:#b00020">NEW</b>' : ''}</div>
<div style="font-size:16px;font-weight:600;margin:4px 0">${esc(e.title)}</div>
${e.titleOriginal ? `<div style="font-size:13px;color:#555">${esc(e.titleOriginal)}</div>` : ''}
<div style="font-size:14px;margin:6px 0">${esc(e.whyRelevant)}</div>
<div style="font-size:12px;color:#555">Sources: ${trail}</div></td></tr>`;
  };
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Regulatory Radar digest ${esc(d.weekEnding)}</title></head>
<body style="font-family:Arial,Helvetica,sans-serif;color:#1b1b1b;max-width:720px;margin:0 auto;padding:16px">
<h1 style="font-size:22px">Regulatory Radar: week ${esc(d.weekStart)} to ${esc(d.weekEnding)}</h1>
<p style="font-size:14px">Countries: ${esc(d.countries.join(', ') || 'all EU')} · NACE: ${esc(d.naceCodes.join(', ') || 'all')}<br>
${d.entries.length} hits out of ${d.groupsChecked} procedure groups checked, ${d.newKeys.size} new this week. Most urgent first.</p>
<table role="presentation" style="width:100%;border-collapse:collapse">${d.entries.map(row).join('\n')}</table>
<p style="font-size:12px;color:#555">Generated by Regulatory Radar. Synthetic seed data is not an official position.</p>
</body></html>`;
};
